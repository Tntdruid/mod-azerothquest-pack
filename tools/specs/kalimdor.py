def quest(id, giver, giver_name, title, sort, min, max, log, text, ret, ask, done, races=0, kill=(), item=None,
          emote=1):
    result = dict(id=id, giver=giver, giver_name=giver_name, title=title, sort=sort, min=min, max=max, log=log,
                  text=text, ask=ask, done=done, races=races, kill=list(kill), emote=emote)
    result["return"] = ret
    if item:
        result["item"] = item
    return result


